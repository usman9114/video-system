#!/usr/bin/env python3
"""kgpu: run a job folder on a free Kaggle GPU, like `docker run`, from this cloud session.

    python -m lane.kgpu whoami
    python -m lane.kgpu run jobs/hello-gpu [--input FILE_OR_DIR ...] [--no-gpu] [--no-internet]
                                            [--timeout-min 60] [--no-wait]
    python -m lane.kgpu status hello-gpu
    python -m lane.kgpu output hello-gpu
    python -m lane.kgpu quota                  # weekly GPU hours used/left
    python -m lane.kgpu clean hello-gpu        # delete the private input dataset + notebook on Kaggle

A job folder contains:
    run.py              entry point (required). Reads inputs from $KGPU_INPUT, writes results to $KGPU_OUTPUT
    requirements.txt    optional, pip-installed on Kaggle before run.py
    any other files     copied alongside run.py

Auth: the Kaggle token is a network secret on the cloud environment. The proxy injects it as
`Authorization: Bearer ...` on requests to api.kaggle.com. We pass a placeholder token and skip the CLI's
token introspection (that call puts the token in the request *body*, which the proxy can't fill).
Everything is created PRIVATE. Docs: docs/kaggle-gpu-setup.md
"""
from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / "kaggle"                       # gitignored: build/, outputs/
USAGE = ROOT / "reports" / "gpu-usage.jsonl"
PREFIX = "kgpu-"
MARKER = ".kgpu_inputs"

os.environ.setdefault("KAGGLE_API_TOKEN", "proxy-injected")


def _api():
    with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
        from kaggle.api.kaggle_api_extended import KaggleApi  # noqa: E402  (package init may print auth help)
    user = os.environ.get("KGPU_USER") or _detect_user()
    KaggleApi._introspect_token = lambda self, tok: user  # see module docstring
    api = KaggleApi()
    api.authenticate()
    return api, user


def _detect_user() -> str:
    from kagglesdk import KaggleClient, KaggleEnv
    from kagglesdk.kernels.types.kernels_api_service import ApiListKernelsRequest
    from kagglesdk.kernels.types.kernels_enums import KernelsListViewType
    with KaggleClient(env=KaggleEnv.PROD, api_token=os.environ["KAGGLE_API_TOKEN"]) as k:
        r = ApiListKernelsRequest()
        r.page_size = 1
        r.group = KernelsListViewType.PROFILE
        ks = k.kernels.kernels_api_client.list_kernels(r).kernels
    if not ks:
        sys.exit("kgpu: can't detect your Kaggle username (no notebooks yet). Set KGPU_USER=<username>.")
    return ks[0].ref.split("/")[0]


def _slug(name: str) -> str:
    s = "".join(c if c.isalnum() else "-" for c in name.lower()).strip("-")
    return (PREFIX + s)[:44]


ENTRY = r'''
# Generated by kgpu. Runs the user's run.py with inputs/outputs wired up.
import os, subprocess, sys, pathlib, time, json
t0 = time.time()
inp = next((str(p.parent) for p in pathlib.Path("/kaggle/input").rglob("{marker}")), "")
out = "/kaggle/working/out"; os.makedirs(out, exist_ok=True)
src = pathlib.Path(__file__).resolve().parent
job = next((str(p.parent) for p in pathlib.Path("/kaggle/input").rglob("run.py")
            if (p.parent / ".kgpu_job").exists()), "")
if not job:
    sys.exit("kgpu: job/run.py not mounted (dataset not attached?)")
env = dict(os.environ, KGPU_INPUT=inp, KGPU_OUTPUT=out)
print("kgpu: inputs at", inp or "(none)", "| job at", job, flush=True)
subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv || true", shell=True)
req = pathlib.Path(job) / "requirements.txt"
if req.exists():
    subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", "-r", str(req)])
rc = subprocess.call([sys.executable, str(pathlib.Path(job) / "run.py")], cwd=out, env=env)
json.dump({{"exit_code": rc, "seconds": round(time.time() - t0, 1)}}, open(out + "/_kgpu_result.json", "w"))
sys.exit(rc)
'''


def _wait_dataset(api, ref: str, limit_s: int = 600) -> None:
    t = time.time()
    while time.time() - t < limit_s:
        try:
            st = str(api.dataset_status(ref)).lower()
        except Exception as e:  # dataset may not be visible yet
            st = f"pending ({e.__class__.__name__})"
        if "ready" in st:
            return
        if "error" in st or "fail" in st:
            sys.exit(f"kgpu: dataset {ref} failed: {st}")
        time.sleep(10)
    sys.exit(f"kgpu: dataset {ref} not ready after {limit_s}s")


def _dataset_exists(api, user: str, slug: str) -> bool:
    try:
        api.dataset_status(f"{user}/{slug}")
        return True
    except Exception:
        return False


def _upload_bundle(api, user: str, job_dir: Path, inputs: list[str], slug: str) -> str:
    """One private dataset per job: the job code + its inputs."""
    d = WORK / "build" / slug / "dataset"
    shutil.rmtree(d, ignore_errors=True)
    (d / "job").mkdir(parents=True)
    for f in job_dir.iterdir():
        if f.is_file():
            shutil.copy2(f, d / "job" / f.name)
    (d / "job" / ".kgpu_job").write_text("1")
    (d / "inputs").mkdir()
    (d / "inputs" / MARKER).write_text("1")
    for i in inputs:
        p = Path(i)
        if p.is_dir():
            shutil.copytree(p, d / "inputs" / p.name)
        elif p.is_file():
            shutil.copy2(p, d / "inputs" / p.name)
        else:
            sys.exit(f"kgpu: input not found: {i}")
    meta = {"title": slug, "id": f"{user}/{slug}", "licenses": [{"name": "unknown"}]}
    (d / "dataset-metadata.json").write_text(json.dumps(meta, indent=1))
    with contextlib.redirect_stdout(io.StringIO()):
        if _dataset_exists(api, user, slug):
            api.dataset_create_version(str(d), version_notes="kgpu run", dir_mode="zip", quiet=True,
                                       delete_old_versions=True)
        else:
            api.dataset_create_new(str(d), public=False, dir_mode="zip", quiet=True)
    _wait_dataset(api, f"{user}/{slug}")
    return f"{user}/{slug}"


def cmd_run(a) -> None:
    api, user = _api()
    job_dir = Path(a.job).resolve()
    if not (job_dir / "run.py").exists():
        sys.exit(f"kgpu: {job_dir}/run.py missing")
    slug = _slug(job_dir.name)
    print(f"kgpu: uploading job + {len(a.input)} input(s) as a fresh private dataset ...", flush=True)
    # a FRESH dataset per run: re-versioning one dataset races with Kaggle's processing (the notebook got the old
    # version, or none at all). docs/LESSONS.md #36
    run_id = format(int(time.time()) % 36 ** 5, "x")
    ds = _upload_bundle(api, user, job_dir, a.input, f"{slug}-d{run_id}")
    (WORK / "build" / slug / "last_dataset.txt").write_text(ds)
    k = WORK / "build" / slug / "kernel"
    shutil.rmtree(k, ignore_errors=True)
    k.mkdir(parents=True)
    (k / "kgpu_entry.py").write_text(ENTRY.format(marker=MARKER))
    meta = {
        "id": f"{user}/{slug}", "title": slug, "code_file": "kgpu_entry.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": not a.no_gpu, "enable_internet": not a.no_internet,
        "dataset_sources": [ds], "competition_sources": [], "kernel_sources": [],
    }
    (k / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    r = api.kernels_push(str(k), timeout=str(a.timeout_min * 60), acc=None if a.no_gpu else a.acc)
    err = getattr(r, "error", None)
    if err:
        sys.exit(f"kgpu: push failed: {err}")
    print(f"kgpu: started {user}/{slug} (GPU={'off' if a.no_gpu else 'on'}) {getattr(r, 'url', '')}", flush=True)
    _log({"job": slug, "event": "start", "gpu": not a.no_gpu})
    if a.no_wait:
        return
    _wait_and_fetch(api, user, slug, a.timeout_min)


def _status(api, ref: str) -> str:
    s = api.kernels_status(ref)
    st = getattr(s, "status", s)
    return str(getattr(st, "name", st)).lower()


def _wait_and_fetch(api, user: str, slug: str, timeout_min: int) -> None:
    ref = f"{user}/{slug}"
    t0 = time.time()
    last = ""
    while True:
        st = _status(api, ref)
        if st != last:
            print(f"kgpu: [{int(time.time() - t0)}s] {st}", flush=True)
            last = st
        if any(x in st for x in ("complete", "error", "cancel")):
            break
        if time.time() - t0 > timeout_min * 60 + 300:
            sys.exit("kgpu: timed out waiting; check later with `kgpu status`")
        time.sleep(30)
    out = _fetch(api, ref, slug)
    _log({"job": slug, "event": "end", "status": st, "wall_s": round(time.time() - t0)})
    res = out / "out" / "_kgpu_result.json"
    print(f"kgpu: {st}. outputs -> {out}")
    if res.exists():
        print("kgpu: result", res.read_text().strip())
    if "complete" not in st:
        sys.exit(1)


def _fetch(api, ref: str, slug: str) -> Path:
    out = WORK / "outputs" / slug
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    api.kernels_output(ref, str(out), force=True, quiet=True)
    return out


def _log(rec: dict) -> None:
    USAGE.parent.mkdir(parents=True, exist_ok=True)
    rec["at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    with USAGE.open("a") as f:
        f.write(json.dumps(rec) + "\n")


def main() -> None:
    p = argparse.ArgumentParser(prog="kgpu", description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("whoami")
    r = sub.add_parser("run")
    r.add_argument("job")
    r.add_argument("--input", action="append", default=[])
    r.add_argument("--no-gpu", action="store_true")
    r.add_argument("--no-internet", action="store_true")
    r.add_argument("--timeout-min", type=int, default=60)
    r.add_argument("--no-wait", action="store_true")
    r.add_argument("--acc", default="NvidiaTeslaT4", help="Kaggle machine shape (NvidiaTeslaT4 = 2x T4)")
    sub.add_parser("quota")
    for n in ("status", "output", "wait", "clean"):
        sub.add_parser(n).add_argument("job")
    a = p.parse_args()

    if a.cmd == "whoami":
        _, user = _api()
        print(user)
        return
    if a.cmd == "run":
        cmd_run(a)
        return
    if a.cmd == "quota":
        api, _ = _api()
        q = api.quota_view()
        for name in ("gpu_quota", "tpu_quota"):
            v = getattr(q, name, None)
            print(name, v.to_dict() if hasattr(v, "to_dict") else v)
        print("refresh:", getattr(q, "quota_refresh_time", None))
        return
    api, user = _api()
    slug = a.job if a.job.startswith(PREFIX) else _slug(Path(a.job).name)
    ref = f"{user}/{slug}"
    if a.cmd == "status":
        print(_status(api, ref))
    elif a.cmd == "output":
        print(_fetch(api, ref, slug))
    elif a.cmd == "wait":
        _wait_and_fetch(api, user, slug, 120)
    elif a.cmd == "clean":
        for fn, args in ((api.kernels_delete, (ref,)), (api.dataset_delete, (user, slug + "-data"))):
            try:
                fn(*args, no_confirm=True)
                print("kgpu: deleted", fn.__name__, ref)
            except Exception as e:
                print("kgpu: skip", fn.__name__, e.__class__.__name__, str(e)[:120])


if __name__ == "__main__":
    main()
